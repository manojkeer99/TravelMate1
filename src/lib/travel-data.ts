export function findDestination(query: string) {
  const normalized = query.toLowerCase().trim();
  return destinations.find((item) => item.id === normalized || item.name.toLowerCase().includes(normalized)) ?? destinations[0];
}

export function createItinerary(destinationName: string, days: number, style = "Standard") {
  const destination = findDestination(destinationName);
  const picks = destination.places;
  const safeDays = Math.max(1, Math.min(days || 3, 7));
  return Array.from({ length: safeDays }, (_, index) => {
    const main = picks[index % picks.length] || picks[0];
    const meal = picks.find((place) => place.kind === "restaurant") || picks[0];
    const activity = picks.find((place) => place.kind === "activity") ?? picks[(index + 1) % picks.length] ?? picks[0];
    return {
      day: index + 1,
      title: index === 0 ? `Arrive & meet ${destination.name}` : index === safeDays - 1 ? "A gentle farewell" : `Discover ${destination.name}`,
      items: [
        { id: `day-${index + 1}-visit`, time: "09:00", title: main.name, meta: `${main.location} • ${main.distance ?? "local"}`, location: main.location, durationMinutes: 150, estimatedCost: main.price.includes("Free") ? 0 : 400, notes: "", type: "visit" },
        { id: `day-${index + 1}-food`, time: "13:00", title: meal?.name ?? `Local ${destination.foods[0]} lunch`, meta: meal ? `${meal.price} • local favourite` : "Ask your hotel or guide for a trusted local stop", location: meal?.location ?? destination.name, durationMinutes: 75, estimatedCost: 550, notes: "", type: "food" },
        { id: `day-${index + 1}-activity`, time: "16:30", title: activity.name, meta: `${activity.price} • ${style} pace`, location: activity.location, durationMinutes: 120, estimatedCost: 700, notes: "", type: "activity" },
      ],
    };
  });
}

